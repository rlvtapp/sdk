import assert from 'node:assert/strict';
import { readFileSync, appendFileSync } from 'node:fs';
const read = file => JSON.parse(readFileSync(new URL('../' + file, import.meta.url), 'utf8'));
const manifest = read('packages/typescript/package.json');
const metadata = read('packages/typescript/.poolster/package.json');
const recipe = read('poolster.json');
const tag = process.env.RELEASE_TAG;
assert.match(tag ?? '', /^typescript-v\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/);
const version = tag.slice('typescript-v'.length);
assert.equal(manifest.name, '@relevate/sdk');
assert.equal(manifest.private, undefined);
assert.equal(manifest.version, version);
assert.equal(recipe.openapi.version, version);
assert.equal(metadata.name, manifest.name);
assert.equal(metadata.version, version);
assert.equal(metadata.publisher.registry, 'npm');
assert.equal(manifest.repository.url, 'https://github.com/rlvtapp/sdk.git');
if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `npm-tag=${version.includes('-') ? 'next' : 'latest'}\n`);
console.log(`Release validated: ${manifest.name}@${version} from ${tag}`);
